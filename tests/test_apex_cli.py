import os
import shutil
import tempfile
import unittest
import subprocess
from pathlib import Path

class TestApexCLI(unittest.TestCase):
    def setUp(self):
        self.test_dir = tempfile.mkdtemp()
        self.cli_path = os.path.abspath(
            os.path.join(os.path.dirname(__file__), "..", "scripts", "apex_cli.py")
        )

    def tearDown(self):
        shutil.rmtree(self.test_dir, ignore_errors=True)

    def test_apex_cli_help(self):
        res = subprocess.run(["python", self.cli_path, "--help"], capture_output=True, text=True)
        self.assertEqual(res.returncode, 0)
        self.assertIn("ApexEngine Master CLI", res.stdout)
        self.assertIn("vibe", res.stdout)
        self.assertIn("gate", res.stdout)
        self.assertIn("deps", res.stdout)
        self.assertIn("heal", res.stdout)

    def test_apex_vibe_to_init_pipeline(self):
        res = subprocess.run(
            ["python", self.cli_path, "vibe", "Build an in-memory key-value cache with TTL eviction", "--dir", self.test_dir],
            capture_output=True,
            text=True
        )
        self.assertEqual(res.returncode, 0, f"apex vibe failed: {res.stderr}")
        self.assertIn("Technical Specification", res.stdout)
        
        # Verify context initialized
        active_state = Path(self.test_dir) / ".context" / "active_state.md"
        self.assertTrue(active_state.exists(), ".context/active_state.md must be generated by apex vibe")

    def test_apex_step_command(self):
        # Initialize context first
        subprocess.run(["python", self.cli_path, "init", "--dir", self.test_dir], check=True, capture_output=True)
        res = subprocess.run(
            ["python", self.cli_path, "step", "Completed database migration, next is API route", "--dir", self.test_dir],
            capture_output=True,
            text=True
        )
        self.assertEqual(res.returncode, 0)
        self.assertIn("Recorded step", res.stdout)

        active_state = Path(self.test_dir) / ".context" / "active_state.md"
        content = active_state.read_text(encoding="utf-8")
        self.assertIn("Completed database migration, next is API route", content)


if __name__ == "__main__":
    unittest.main()
